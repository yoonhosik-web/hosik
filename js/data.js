function parseKanji(raw, level) {
  return raw.trim().split("\n").map((line) => {
    const [kanji, on, kun, bushu, ex] = line.split("|");
    const split = (s) => (s === "—" ? [] : s.split("・"));
    return {
      kanji,
      level,
      on: split(on),
      kun: split(kun),
      bushu,
      examples: ex.split(";").map((e) => {
        const [word, yomi] = e.split(":");
        return { word, yomi };
      }),
    };
  });
}

